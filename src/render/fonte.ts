/** Avanço de um caractere, em pixels (3 de glifo mais 1 de espaço). */
export const AVANCO_GLIFO = 4;

/** Largura de um texto. O último caractere não tem espaço depois. */
export function larguraTexto(texto: string, escala = 1): number {
  if (texto.length === 0) return 0;
  return texto.length * AVANCO_GLIFO * escala - escala;
}
